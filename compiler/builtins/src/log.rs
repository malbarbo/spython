//! `math.log`, ported from `src/math/log.c` of musl, which comes from the
//! optimized routines of Arm. glibc has the same routine.
//!
//! As in `pow.rs`, the port calls `fma` at each place where GCC contracts
//! `a * b + c` into `fma` in the build of glibc with FMA.

use libm::fma;

#[unsafe(no_mangle)]
pub extern "C" fn f64_log(x: f64) -> f64 {
    log(x)
}

const TABLE_BITS: u32 = 7;
const N: u64 = 1 << TABLE_BITS;

/// The natural logarithm of `x`, within 0.52 ulp. It is -inf at 0 and nan
/// below 0.
pub fn log(x: f64) -> f64 {
    const ONE: u64 = 0x3ff0000000000000;
    // The bits of `1 - 2^-4` and of `1 + 0x1.09p-4`.
    const LO: u64 = 0x3fee000000000000;
    const HI: u64 = 0x3ff1090000000000;
    const OFF: u64 = 0x3fe6000000000000;
    const LN2_HI: f64 = 0.6931471805598903;
    const LN2_LO: f64 = 5.497923018708371e-14;
    // The coefficients of `log1p(r) - r` for `|r| < 1/2N`.
    const A: [f64; 5] = [
        -0.5000000000000001,
        0.33333333331825593,
        -0.2499999999622955,
        0.20000304511814496,
        -0.16667054827627667,
    ];
    // The coefficients of `log1p(r) - r` near 1, where the table is not
    // precise enough.
    const B: [f64; 11] = [
        -0.5,
        0.3333333333333352,
        -0.24999999999998432,
        0.19999999999320328,
        -0.16666666669929706,
        0.14285715076560868,
        -0.12499997863982555,
        0.11110712032936046,
        -0.10000486757818193,
        0.09181994006195467,
        -0.08328363062289341,
    ];

    let mut ix = x.to_bits();
    if ix.wrapping_sub(LO) < HI - LO {
        if ix == ONE {
            return 0.0;
        }
        let [b0, b1, b2, b3, b4, b5, b6, b7, b8, b9, b10] = B;
        let r = x - 1.0;
        let r2 = r * r;
        let r3 = r * r2;
        let q = fma(r3, b10, fma(r2, b9, fma(r, b8, b7)));
        let q = fma(r3, q, fma(r2, b6, fma(r, b5, b4)));
        let q = fma(r3, q, fma(r2, b3, fma(r, b2, b1)));
        // `rhi` is `r` cut to 26 bits, so `rhi * rhi * b0` is exact.
        let w = r * 134217728.0;
        let rhi = r + w - w;
        let rlo = r - rhi;
        let w = rhi * rhi * b0;
        let hi = r + w;
        let lo = r - hi + w;
        let lo = fma(b0 * rlo, rhi + r, lo);
        return fma(r3, q, lo) + hi;
    }
    let top = (ix >> 48) as u32;
    if top.wrapping_sub(0x0010) >= 0x7ff0 - 0x0010 {
        // `x` is below 2^-1022, infinite or nan.
        if ix << 1 == 0 {
            return f64::NEG_INFINITY;
        }
        if x == f64::INFINITY {
            return x;
        }
        if top & 0x8000 != 0 || top & 0x7ff0 == 0x7ff0 {
            return f64::NAN;
        }
        // A subnormal `x`, normalized with an exponent below the range.
        ix = (x * 4503599627370496.0).to_bits();
        ix = ix.wrapping_sub(52 << 52);
    }

    // `x = 2^k z`, where `z` is in `[OFF, 2 OFF)`. The table splits that
    // range in `N` parts, and `c` is near the center of the part of `z`.
    let tmp = ix.wrapping_sub(OFF);
    let i = (tmp >> (52 - TABLE_BITS)) % N;
    let k = (tmp as i64 >> 52) as i32;
    let iz = ix.wrapping_sub(tmp & 0xfff << 52);
    // `i` is below `N`, so the lookup never fails.
    let Some(&(invc, logc)) = TABLE.get(i as usize) else {
        return f64::NAN;
    };
    let z = f64::from_bits(iz);
    let kd = f64::from(k);
    let [a0, a1, a2, a3, a4] = A;

    // `log(x) = k ln2 + log(c) + log1p(r)`, where `r = z/c - 1`, and `hi +
    // lo` is the sum of the first two with `r`.
    let r = fma(z, invc, -1.0);
    let w = fma(kd, LN2_HI, logc);
    let hi = w + r;
    let lo = fma(kd, LN2_LO, w - hi + r);
    let r2 = r * r;
    let p = fma(r2, fma(r, a4, a3), fma(r, a2, a1));
    fma(r * r2, p, fma(r2, a0, lo)) + hi
}

