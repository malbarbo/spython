/// Each probe that the checker accepts at the last level prints what
/// CPython prints, and exits as CPython exits, in wasmtime and in deno,
/// except the probes of [`EXPECTED`], which have the outcome there.
#[test]
fn each_probe_has_its_outcome() {
    let files = python_files(&probes());
    let outcomes = each_file(&files, |file| run_at(file, Level::Full));
    let wrong: Vec<_> = outcomes
        .iter()
        .filter_map(|(file, outcome)| {
            let name = name(file);
            let expected = EXPECTED
                .iter()
                .find(|(probe, _, _)| *probe == name)
                .map_or(Outcome::Same, |(_, outcome, _)| *outcome);
            (expected != *outcome).then(|| format!("{name}: {outcome:?}, not {expected:?}"))
        })
        .collect();
    assert!(wrong.is_empty(), "probes with another outcome: {wrong:#?}");
    let gone: Vec<_> = EXPECTED
        .iter()
        .filter(|(probe, _, _)| !files.iter().any(|file| name(file) == *probe))
        .collect();
    assert!(gone.is_empty(), "no file for these probes: {gone:#?}");
}

/// The directory of the probes. Each file starts with `probe_`, so that a
/// probe never takes the name of a module of the standard library.
fn probes() -> PathBuf {
    Path::new(env!("CARGO_MANIFEST_DIR")).join("tests/probes")
}

/// The name of the probe in `file`, without `probe_` and `.py`.
fn name(file: &Path) -> &str {
    file.file_stem()
        .and_then(|stem| stem.to_str())
        .and_then(|stem| stem.strip_prefix("probe_"))
        .expect("a probe named probe_*.py")
}
